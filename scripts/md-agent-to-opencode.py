#!/usr/bin/env python3
"""Convert a Claude-Code subagent Markdown file (YAML frontmatter + body)
into an opencode subagent Markdown definition.

Usage: md-agent-to-opencode.py <input.md>
The generated Markdown is written to stdout. Only the standard library is used.

opencode requires the '---' frontmatter fence on the very first line, so the
generated banner is emitted as a YAML comment on the second line (inside the
frontmatter), not as an HTML comment before it.

Tool permissions: Claude's `tools` is an allow-list; opencode's `tools` is a
default-on deny map. We only preserve the read-only invariant: when a Claude
agent's `tools` list is present but contains neither Write nor Edit, we emit
`write: false` / `edit: false` (and `bash: false` too when Bash is also
absent). Agents with write access, or with no `tools` field at all (which in
Claude means full access), get no `tools` block.
"""
import sys

from agent_model_map import resolve_opencode, is_unknown_tier

BANNER = "# GENERATED by install.sh from agents/*.md - do not edit."


def split_frontmatter(text):
    """Return (frontmatter_dict, body). The file must start with a YAML
    frontmatter block delimited by lines that contain only '---'. Only
    top-level 'key: value' scalars are parsed. Raises ValueError when the
    block is absent."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter opening '---'")
    fm = {}
    i = 1
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        if line.strip() and ":" in line:
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip().strip('"')
        i += 1
    if i >= len(lines):
        raise ValueError("missing frontmatter closing '---'")
    body = "\n".join(lines[i + 1:]).strip("\n")
    return fm, body


def yaml_double_quoted(value):
    """Escape a string as a YAML double-quoted scalar."""
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return '"' + out + '"'


def readonly_tools(tools_field):
    """Given the raw Claude `tools` frontmatter value (or None when absent),
    return the opencode tool-lock lines to emit, or [] for none. The
    read-only invariant: tools present but lacking Write and Edit -> lock
    write/edit (and bash too when Bash is also absent)."""
    if tools_field is None:
        return []
    names = [t.strip() for t in tools_field.split(",") if t.strip()]
    if "Write" in names or "Edit" in names:
        return []
    lines = ["tools:", "  write: false", "  edit: false"]
    if "Bash" not in names:
        lines.append("  bash: false")
    return lines


def convert(text, path="<stdin>"):
    fm, body = split_frontmatter(text)
    if "description" not in fm:
        raise ValueError("frontmatter must contain 'description'")
    out = ["---", BANNER,
           "description: " + yaml_double_quoted(fm["description"]),
           "mode: subagent"]
    tier = fm.get("model")
    if is_unknown_tier(tier):
        sys.stderr.write(
            "warning: %s: unknown model tier %r; omitting model field\n"
            % (path, tier))
    model = resolve_opencode(tier)
    if model:
        out.append("model: " + model)
    out.extend(readonly_tools(fm.get("tools")))
    out.append("---")
    out.append(body)
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: md-agent-to-opencode.py <input.md>\n")
        return 2
    with open(argv[1], "r", encoding="utf-8") as f:
        text = f.read()
    try:
        sys.stdout.write(convert(text, argv[1]))
    except ValueError as exc:
        sys.stderr.write("error: %s: %s\n" % (argv[1], exc))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
