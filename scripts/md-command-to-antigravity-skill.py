#!/usr/bin/env python3
"""Convert a Claude-Code slash-command Markdown file into an Antigravity
SKILL.md.

Usage: md-command-to-antigravity-skill.py <input.md> <skill-name>
The generated Markdown is written to stdout. Only the standard library is used.

Antigravity has been migrating its `workflows/` and `global_workflows/`
directories into `skills/`, so this repo's commands ship as skills rather than
workflow files. Antigravity turns a skill into a slash command automatically,
so `/vf-trello-board-sprint-review` keeps working.

The skill name is supplied by the caller rather than derived here: install.sh
flattens the nested command path (commands/vf/x.md -> vf-x) and is the only
place that knows the source root.
"""
import sys

BANNER = "# GENERATED by install.sh from commands/*.md - do not edit."


def split_frontmatter(text):
    """Return (frontmatter_dict, body). The file must start with a YAML
    frontmatter block delimited by lines that contain only '---'. Only
    top-level 'key: value' scalars are parsed. Raises ValueError when the
    block is absent."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter opening '---'")
    fm = {}
    i = 1
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        if line.strip() and ":" in line:
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip().strip('"')
        i += 1
    if i >= len(lines):
        raise ValueError("missing frontmatter closing '---'")
    body = "\n".join(lines[i + 1:]).strip("\n")
    return fm, body


def yaml_double_quoted(value):
    """Escape a string as a YAML double-quoted scalar."""
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return '"' + out + '"'


def convert(text, name, path="<stdin>"):
    fm, body = split_frontmatter(text)
    if "description" not in fm:
        raise ValueError("frontmatter must contain 'description'")
    out = ["---", BANNER,
           "name: " + name,
           "description: " + yaml_double_quoted(fm["description"]),
           "---",
           body]
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 3:
        sys.stderr.write(
            "usage: md-command-to-antigravity-skill.py <input.md> <skill-name>\n")
        return 2
    with open(argv[1], "r", encoding="utf-8") as f:
        text = f.read()
    try:
        sys.stdout.write(convert(text, argv[2], argv[1]))
    except ValueError as exc:
        sys.stderr.write("error: %s: %s\n" % (argv[1], exc))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
