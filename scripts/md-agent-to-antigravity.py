#!/usr/bin/env python3
"""Convert a Claude-Code subagent Markdown file (YAML frontmatter + body)
into an Antigravity subagent Markdown definition.

Usage: md-agent-to-antigravity.py <input.md>
The generated Markdown is written to stdout. Only the standard library is used.

Antigravity requires the '---' frontmatter fence on the very first line, so
the generated banner is emitted as a YAML comment on the second line (inside
the frontmatter), the same way the opencode converter does it.

The `tools` field is deliberately never emitted. Claude's tool names
(Read/Grep/Bash) and Antigravity's (view_file/grep_search/run_command) are two
different vocabularies; a partial mapping would silently narrow a subagent's
permissions, and a subagent missing a tool fails half-way through a task -
harder to trace than an over-broad one. Omitting the field applies the
platform default instead.
"""
import os
import sys

from agent_model_map import resolve_antigravity, is_unknown_tier

BANNER = "# GENERATED by install.sh from agents/*.md - do not edit."


def split_frontmatter(text):
    """Return (frontmatter_dict, body). The file must start with a YAML
    frontmatter block delimited by lines that contain only '---'. Only
    top-level 'key: value' scalars are parsed. Raises ValueError when the
    block is absent."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter opening '---'")
    fm = {}
    i = 1
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        if line.strip() and ":" in line:
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip().strip('"')
        i += 1
    if i >= len(lines):
        raise ValueError("missing frontmatter closing '---'")
    body = "\n".join(lines[i + 1:]).strip("\n")
    return fm, body


def yaml_double_quoted(value):
    """Escape a string as a YAML double-quoted scalar."""
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return '"' + out + '"'


def convert(text, path="<stdin>"):
    fm, body = split_frontmatter(text)
    if "description" not in fm:
        raise ValueError("frontmatter must contain 'description'")
    # Claude agent files always carry `name`, but fall back to the filename
    # stem so a hand-made file without one still converts.
    name = fm.get("name") or os.path.splitext(os.path.basename(path))[0]
    out = ["---", BANNER,
           "name: " + name,
           "description: " + yaml_double_quoted(fm["description"]),
           "mainAgent: false",
           "subagent: true"]
    tier = fm.get("model")
    if is_unknown_tier(tier):
        sys.stderr.write(
            "warning: %s: unknown model tier %r; omitting model field\n"
            % (path, tier))
    model = resolve_antigravity(tier)
    if model:
        out.append("model: " + model)
    out.append("---")
    out.append(body)
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: md-agent-to-antigravity.py <input.md>\n")
        return 2
    with open(argv[1], "r", encoding="utf-8") as f:
        text = f.read()
    try:
        sys.stdout.write(convert(text, argv[1]))
    except ValueError as exc:
        sys.stderr.write("error: %s: %s\n" % (argv[1], exc))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
