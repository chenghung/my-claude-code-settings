#!/usr/bin/env python3
"""Convert a Claude-Code subagent Markdown file (YAML frontmatter + body)
into a Codex subagent TOML definition.

Usage: md-agent-to-toml.py <input.md>
The generated TOML is written to stdout. Only the standard library is used;
the stdlib has no TOML writer, so the output is emitted by hand with explicit
escaping.
"""
import sys

BANNER = "# GENERATED by install.sh from agents/*.md - do not edit."


def split_frontmatter(text):
    """Return (frontmatter_dict, body). The file must start with a YAML
    frontmatter block delimited by lines that contain only '---'. Only
    top-level 'key: value' scalars are parsed, which is all subagent
    frontmatter needs. Raises ValueError when the block is absent."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter opening '---'")
    fm = {}
    i = 1
    while i < len(lines) and lines[i].strip() != "---":
        line = lines[i]
        if line.strip() and ":" in line:
            key, _, value = line.partition(":")
            fm[key.strip()] = value.strip().strip('"')
        i += 1
    if i >= len(lines):
        raise ValueError("missing frontmatter closing '---'")
    body = "\n".join(lines[i + 1:]).strip("\n")
    return fm, body


def toml_basic_string(value):
    """Escape a string as a TOML basic (double-quoted) string."""
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")
    return '"' + out + '"'


def toml_multiline_string(value):
    """Escape a string as a TOML multiline basic string. Backslashes are
    doubled so no escape sequence or line-continuation is interpreted, and
    any triple-quote run is broken so it cannot close the string early."""
    out = value.replace("\\", "\\\\")
    out = out.replace('"""', '""\\"')
    return '"""\n' + out + '\n"""'


def convert(text):
    fm, body = split_frontmatter(text)
    if "name" not in fm or "description" not in fm:
        raise ValueError("frontmatter must contain 'name' and 'description'")
    lines = [
        BANNER,
        "name = " + toml_basic_string(fm["name"]),
        "description = " + toml_basic_string(fm["description"]),
        "developer_instructions = " + toml_multiline_string(body),
        "",
    ]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: md-agent-to-toml.py <input.md>\n")
        return 2
    with open(argv[1], "r", encoding="utf-8") as f:
        text = f.read()
    try:
        sys.stdout.write(convert(text))
    except ValueError as exc:
        sys.stderr.write("error: %s: %s\n" % (argv[1], exc))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
