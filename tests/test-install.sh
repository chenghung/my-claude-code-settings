#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
# Every install.sh run in this file - and every program it starts - sees a
# HOME under $T, so no run can reach the real HOME even if a call site forgets
# --no-external or one of the directory overrides below.
export HOME="$T/home"
mkdir -p "$HOME"
# Safety guard: abort the whole suite if HOME is not under $T.
if [[ "$HOME" != "$T"/* ]]; then
  printf 'FATAL HOME=%s is not under %s - aborting\n' "$HOME" "$T" >&2
  exit 1
fi
export CLAUDE_CONFIG_DIR="$T/claude"
export CODEX_HOME="$T/codex"
export AGENTS_HOME="$T/agents"
export GEMINI_HOME="$T/gemini"
# Default export so the agy stub's `${AGY_STUB_LOG:?}` expansion (further
# down) can never abort on an unset variable, even if some future call site
# forgets to (re)assign it before invoking the stub; scenario-specific blocks
# below reassign this to their own log path, which keeps the export attribute.
export AGY_STUB_LOG="$T/agy-stub.log"
# Test-only escape hatch: skip install-cli-tools.sh so this suite never
# triggers real sudo pacman/yay installs.
export INSTALL_CLI_TOOLS=0
# Test-only override, same idea as INSTALL_CLI_TOOLS: install.sh runs this
# stub instead of the real sync-external-skills.sh, which would run the real
# `npx skills add/remove` over the network. Exported before the first
# install.sh run so it covers the whole file. The stub appends its argv to
# SYNC_STUB_LOG, prints install-like lines (used to prove install.sh does not
# count them) and exits with SYNC_STUB_EXIT (default 0).
export SYNC_EXTERNAL_SKILLS="$T/sync-stub"
export SYNC_STUB_LOG="$T/sync-stub.log"
cat > "$SYNC_EXTERNAL_SKILLS" <<'STUB'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "${SYNC_STUB_LOG:?}"
printf '  INSTALLED fake-skill (claude-code)\n'
printf '  CREATED  fake\n'
exit "${SYNC_STUB_EXIT:-0}"
STUB
chmod +x "$SYNC_EXTERNAL_SKILLS"

"$REPO/install.sh" --codex --no-external > "$T/log1" 2>&1

if test -L "$AGENTS_HOME/skills/deep-thinking"; then pass skills-symlink; else bad skills-symlink; fi
if test -L "$CODEX_HOME/prompts/vf-trello-board-sprint-review.md"; then pass cmd-flatten; else bad cmd-flatten; fi
if test -f "$CODEX_HOME/config.toml"; then pass config-seeded; else bad config-seeded; fi

# AGENTS.md is generated and contains CLAUDE.md + rules content
if test -f "$CODEX_HOME/AGENTS.md"; then pass agents-md-exists; else bad agents-md-exists; fi
if grep -q 'Think Before Coding' "$CODEX_HOME/AGENTS.md"; then pass agents-md-claude; else bad agents-md-claude; fi
if grep -q 'Routing Table' "$CODEX_HOME/AGENTS.md"; then pass agents-md-rules; else bad agents-md-rules; fi
if grep -q 'ripgrep' "$CODEX_HOME/AGENTS.md"; then pass agents-md-search-rule; else bad agents-md-search-rule; fi
if grep -q 'CodeGraph' "$CODEX_HOME/AGENTS.md"; then pass agents-md-codegraph; else bad agents-md-codegraph; fi

# Subagent TOMLs are generated
if test -f "$CODEX_HOME/agents/docker-expert.toml"; then pass toml-exists; else bad toml-exists; fi
if head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh'; then pass toml-banner; else bad toml-banner; fi

# Idempotent second run
"$REPO/install.sh" --codex --no-external > "$T/log2" 2>&1
if grep -q 'CONFLICT' "$T/log2"; then bad idempotent; else pass idempotent; fi

# Prune removes an orphaned generated TOML
printf '# GENERATED by install.sh from agents/*.md - do not edit.\nname = "gone"\n' > "$CODEX_HOME/agents/gone.toml"
"$REPO/install.sh" --codex --no-external > "$T/log3" 2>&1
if test ! -f "$CODEX_HOME/agents/gone.toml"; then pass prune; else bad prune; fi

# Prune does NOT remove a hand-authored TOML (no banner)
printf 'name = "handmade"\n' > "$CODEX_HOME/agents/handmade.toml"
"$REPO/install.sh" --codex --no-external > "$T/log4" 2>&1
if test -f "$CODEX_HOME/agents/handmade.toml"; then pass keep-handmade; else bad keep-handmade; fi

# Generate step does NOT overwrite a hand-authored TOML that collides with a
# repo agent name (docker-expert.toml collides with agents/docker-expert.md)
printf 'name = "my-handwritten"\n' > "$CODEX_HOME/agents/docker-expert.toml"
"$REPO/install.sh" --codex --no-external > "$T/log5" 2>&1
if grep -q 'my-handwritten' "$CODEX_HOME/agents/docker-expert.toml"; then pass keep-handmade-collision; else bad keep-handmade-collision; fi
if head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh'; then bad keep-handmade-collision-banner; else pass keep-handmade-collision-banner; fi

# ---- opencode ----
export OPENCODE_CONFIG_DIR="$T/opencode"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc1" 2>&1

# skills reuse the shared ~/.agents/skills dir
if test -L "$AGENTS_HOME/skills/deep-thinking"; then pass oc-skills; else bad oc-skills; fi
# commands flattened into opencode commands dir
if test -L "$OPENCODE_CONFIG_DIR/commands/vf-trello-board-sprint-review.md"; then pass oc-cmd; else bad oc-cmd; fi
# opencode.json symlinked
if test -L "$OPENCODE_CONFIG_DIR/opencode.json"; then pass oc-config; else bad oc-config; fi
# AGENTS.md generated with rules content
if grep -q 'Routing Table' "$OPENCODE_CONFIG_DIR/AGENTS.md"; then pass oc-agents-md; else bad oc-agents-md; fi
# subagent md generated; frontmatter fence on line 1, banner on line 2
if test -f "$OPENCODE_CONFIG_DIR/agents/docker-expert.md"; then pass oc-agent-exists; else bad oc-agent-exists; fi
if head -1 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -qx -- '---'; then pass oc-agent-fm; else bad oc-agent-fm; fi
if head -3 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -q 'GENERATED by install.sh'; then pass oc-agent-banner; else bad oc-agent-banner; fi
# a read-only agent has write disabled
if grep -q 'write: false' "$OPENCODE_CONFIG_DIR/agents/adversarial-thinker.md"; then pass oc-agent-readonly; else bad oc-agent-readonly; fi

# idempotent second run
"$REPO/install.sh" --opencode --no-external > "$T/log_oc2" 2>&1
if grep -q 'CONFLICT' "$T/log_oc2"; then bad oc-idempotent; else pass oc-idempotent; fi

# prune orphaned generated agent md (banner on second line)
printf -- '---\n# GENERATED by install.sh from agents/*.md - do not edit.\ndescription: "gone"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/gone.md"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc3" 2>&1
if test ! -f "$OPENCODE_CONFIG_DIR/agents/gone.md"; then pass oc-prune; else bad oc-prune; fi

# keep hand-authored agent md (no banner)
printf -- '---\ndescription: "handmade"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/handmade.md"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc4" 2>&1
if test -f "$OPENCODE_CONFIG_DIR/agents/handmade.md"; then pass oc-keep-handmade; else bad oc-keep-handmade; fi

# ---- codegraph MCP registration (Claude Code): real behavior, not string match ----
# Stub `claude` logs every invocation ($* per call, one line) and lets
# `mcp get codegraph`'s exit code be controlled via CLAUDE_MCP_GET_EXIT, so
# both branches of register_codegraph_mcp can be exercised without a real
# claude CLI or network access.
STUB_BIN="$T/stub-bin"
mkdir -p "$STUB_BIN"
cat > "$STUB_BIN/claude" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${CLAUDE_STUB_LOG:?}"
if [ "${1:-}" = "mcp" ] && [ "${2:-}" = "get" ]; then
  exit "${CLAUDE_MCP_GET_EXIT:-0}"
fi
exit 0
STUB
chmod +x "$STUB_BIN/claude"

# Scenario A: codegraph not yet registered (mcp get exits 1) -> install.sh
# must call `claude mcp add codegraph --scope user -- codegraph serve --mcp`.
export CLAUDE_CONFIG_DIR="$T/claude-notreg"
CLAUDE_STUB_LOG="$T/claude-stub-notreg.log"
: > "$CLAUDE_STUB_LOG"
# shellcheck disable=SC2030  # PATH/CLAUDE_MCP_GET_EXIT are deliberately modified only inside this subshell (same idiom as run_settings_deploy below)
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=1; "$REPO/install.sh" --claude --no-external > "$T/log_claude_notreg" 2>&1 )
if grep -qxF 'mcp add codegraph --scope user -- codegraph serve --mcp' "$CLAUDE_STUB_LOG"; then pass codegraph-mcp-registers-when-absent; else bad codegraph-mcp-registers-when-absent; fi

# Scenario B: codegraph already registered (mcp get exits 0) -> install.sh
# must NOT call `claude mcp add` at all.
export CLAUDE_CONFIG_DIR="$T/claude-reg"
CLAUDE_STUB_LOG="$T/claude-stub-reg.log"
: > "$CLAUDE_STUB_LOG"
# shellcheck disable=SC2030,SC2031  # PATH/CLAUDE_MCP_GET_EXIT are deliberately modified only inside this subshell (same idiom as run_settings_deploy below)
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude --no-external > "$T/log_claude_reg" 2>&1 )
if grep -q '^mcp add' "$CLAUDE_STUB_LOG"; then bad codegraph-mcp-skips-when-registered; else pass codegraph-mcp-skips-when-registered; fi

# ---- settings.json is no longer symlinked: migration cases ----
# install.sh stops symlinking ~/.claude/settings.json (clauth owns it; the
# repo copy is loaded with `--settings`, see platforms/claude/clauth.zsh).
# Devices deployed by an older install.sh still hold the symlink, so each
# starting state gets a fresh CLAUDE_CONFIG_DIR and the stubbed claude (the
# codegraph registration step must never reach the real CLI):
#   symlink to the repo file -> real-file copy; real file -> untouched;
#   missing -> nothing created; symlink elsewhere -> untouched.
REPO_SETTINGS="$REPO/platforms/claude/settings.json"
REPO_SETTINGS_SUM="$(sha256sum "$REPO_SETTINGS" | cut -d' ' -f1)"
run_settings_deploy() { # $1 = log path; uses the current CLAUDE_CONFIG_DIR
  CLAUDE_STUB_LOG="$T/claude-stub-settings.log"
  : > "$CLAUDE_STUB_LOG"
  # Shadow guard (gating): `claude` is the only external program the --claude
  # deploy runs that could reach a real, stateful binary. It must resolve to
  # the stub under the exact PATH the subshell below uses; otherwise the
  # deploy is NOT run at all and the case fails loudly.
  # shellcheck disable=SC2031  # PATH is only ever set per-command/subshell here; reading the outer PATH is intended
  if [ "$(PATH="$STUB_BIN:$PATH" command -v claude 2>/dev/null || true)" != "$STUB_BIN/claude" ]; then
    bad settings-deploy-claude-shadow-guard
    : > "$1"
    return 0
  fi
  # shellcheck disable=SC2030,SC2031  # PATH is deliberately modified only inside this subshell (same idiom as the scenarios above)
  ( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude --no-external > "$1" 2>&1 )
}

# Case 1: symlink to the repo file -> replaced by a real-file copy.
export CLAUDE_CONFIG_DIR="$T/claude-settings-link"
mkdir -p "$CLAUDE_CONFIG_DIR"
ln -s "$REPO_SETTINGS" "$CLAUDE_CONFIG_DIR/settings.json"
run_settings_deploy "$T/log_settings_link"
if test -f "$CLAUDE_CONFIG_DIR/settings.json" && test ! -L "$CLAUDE_CONFIG_DIR/settings.json"; then pass settings-symlink-becomes-real-file; else bad settings-symlink-becomes-real-file; fi
if [ "$(sha256sum "$CLAUDE_CONFIG_DIR/settings.json" | cut -d' ' -f1)" = "$REPO_SETTINGS_SUM" ]; then pass settings-migrated-copy-matches-repo; else bad settings-migrated-copy-matches-repo; fi
if grep -q "MIGRATED $CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_link"; then pass settings-migrated-reported; else bad settings-migrated-reported; fi
# no backup file, no leftover temp copy
if compgen -G "$CLAUDE_CONFIG_DIR/settings.json.*" >/dev/null; then bad settings-migration-leaves-no-extra-files; else pass settings-migration-leaves-no-extra-files; fi
# the repo file itself is neither replaced nor modified
if { test -f "$REPO_SETTINGS" && test ! -L "$REPO_SETTINGS" && [ "$(sha256sum "$REPO_SETTINGS" | cut -d' ' -f1)" = "$REPO_SETTINGS_SUM" ]; }; then pass settings-repo-file-untouched; else bad settings-repo-file-untouched; fi
# CLAUDE.md keeps its backup_migrate_link symlink behaviour
if test -L "$CLAUDE_CONFIG_DIR/CLAUDE.md"; then pass settings-claude-md-still-symlinked; else bad settings-claude-md-still-symlinked; fi
# A second run sees a real file: reported OK, content unchanged, no CONFLICT
run_settings_deploy "$T/log_settings_link2"
if grep -q "OK       $CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_link2" && ! grep -q 'CONFLICT' "$T/log_settings_link2"; then pass settings-migration-idempotent; else bad settings-migration-idempotent; fi

# Case 2: a real file is left untouched (content and not replaced).
export CLAUDE_CONFIG_DIR="$T/claude-settings-real"
mkdir -p "$CLAUDE_CONFIG_DIR"
printf '{"hand":"written"}\n' > "$CLAUDE_CONFIG_DIR/settings.json"
run_settings_deploy "$T/log_settings_real"
if { test ! -L "$CLAUDE_CONFIG_DIR/settings.json" && [ "$(cat "$CLAUDE_CONFIG_DIR/settings.json")" = '{"hand":"written"}' ]; }; then pass settings-real-file-untouched; else bad settings-real-file-untouched; fi
if grep -q "OK       $CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_real"; then pass settings-real-file-reported-ok; else bad settings-real-file-reported-ok; fi
if compgen -G "$CLAUDE_CONFIG_DIR/settings.json.*" >/dev/null; then bad settings-real-file-no-backup; else pass settings-real-file-no-backup; fi

# Case 3: missing -> nothing is created and nothing is reported about it.
export CLAUDE_CONFIG_DIR="$T/claude-settings-missing"
run_settings_deploy "$T/log_settings_missing"
if { test ! -e "$CLAUDE_CONFIG_DIR/settings.json" && test ! -L "$CLAUDE_CONFIG_DIR/settings.json"; }; then pass settings-missing-stays-missing; else bad settings-missing-stays-missing; fi
if grep -q "$CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_missing"; then bad settings-missing-not-reported; else pass settings-missing-not-reported; fi
if grep -qE '^  (MIGRATED|CONFLICT|OK) .*settings\.json' "$T/log_settings_missing"; then bad settings-missing-no-status-line; else pass settings-missing-no-status-line; fi

# Extra: a symlink pointing somewhere other than any repo settings.json is not ours to
# replace; it is reported as CONFLICT and left as is.
export CLAUDE_CONFIG_DIR="$T/claude-settings-foreign"
mkdir -p "$CLAUDE_CONFIG_DIR"
printf '{"foreign":true}\n' > "$T/foreign-settings.json"
ln -s "$T/foreign-settings.json" "$CLAUDE_CONFIG_DIR/settings.json"
run_settings_deploy "$T/log_settings_foreign"
if { test -L "$CLAUDE_CONFIG_DIR/settings.json" && [ "$(readlink "$CLAUDE_CONFIG_DIR/settings.json")" = "$T/foreign-settings.json" ]; }; then pass settings-foreign-symlink-untouched; else bad settings-foreign-symlink-untouched; fi
if grep -q "CONFLICT $CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_foreign"; then pass settings-foreign-symlink-reported; else bad settings-foreign-symlink-reported; fi
# The CONFLICT message says clauth will replace the link at runtime.
if grep -q 'clauth will replace this symlink at runtime' "$T/log_settings_foreign"; then pass settings-foreign-conflict-explains; else bad settings-foreign-conflict-explains; fi

# A symlink to a DIFFERENT copy of this repo (another clone / git worktree)
# is also migrated, to a copy of THIS repo's file - never of the other one.
export CLAUDE_CONFIG_DIR="$T/claude-settings-otherclone"
mkdir -p "$CLAUDE_CONFIG_DIR" "$T/other clone/platforms/claude"
printf '{"other":"clone"}\n' > "$T/other clone/platforms/claude/settings.json"
ln -s "$T/other clone/platforms/claude/settings.json" "$CLAUDE_CONFIG_DIR/settings.json"
run_settings_deploy "$T/log_settings_otherclone"
if { test -f "$CLAUDE_CONFIG_DIR/settings.json" && test ! -L "$CLAUDE_CONFIG_DIR/settings.json" && [ "$(sha256sum "$CLAUDE_CONFIG_DIR/settings.json" | cut -d' ' -f1)" = "$REPO_SETTINGS_SUM" ]; }; then pass settings-otherclone-symlink-migrated-to-this-repo; else bad settings-otherclone-symlink-migrated-to-this-repo; fi
if [ "$(cat "$T/other clone/platforms/claude/settings.json")" = '{"other":"clone"}' ]; then pass settings-otherclone-file-untouched; else bad settings-otherclone-file-untouched; fi
if grep -q "MIGRATED $CLAUDE_CONFIG_DIR/settings.json" "$T/log_settings_otherclone"; then pass settings-otherclone-reported; else bad settings-otherclone-reported; fi

# A relative symlink target (resolving to a repo copy) is migrated too.
export CLAUDE_CONFIG_DIR="$T/claude-settings-relative"
mkdir -p "$CLAUDE_CONFIG_DIR"
ln -s "../other clone/platforms/claude/settings.json" "$CLAUDE_CONFIG_DIR/settings.json"
run_settings_deploy "$T/log_settings_relative"
if { test -f "$CLAUDE_CONFIG_DIR/settings.json" && test ! -L "$CLAUDE_CONFIG_DIR/settings.json" && [ "$(sha256sum "$CLAUDE_CONFIG_DIR/settings.json" | cut -d' ' -f1)" = "$REPO_SETTINGS_SUM" ]; }; then pass settings-relative-symlink-migrated; else bad settings-relative-symlink-migrated; fi


# ---- Antigravity CLI ----
# Stub `agy` before any --antigravity run: once register_codegraph_mcp_antigravity
# exists, an unstubbed run would reach the real agy on this machine and mutate
# the developer's live MCP config. AGY_MCP_HAS_CODEGRAPH switches the two
# branches of that function; the log lets later scenarios assert on calls.
cat > "$STUB_BIN/agy" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${AGY_STUB_LOG:?}"
if [ "${1:-}" = "mcp" ] && [ "${2:-}" = "list" ]; then
  if [ "${AGY_MCP_HAS_CODEGRAPH:-0}" = "1" ]; then
    printf 'NAME        TYPE   STATUS   COMMAND/URL\n'
    printf 'codegraph   stdio  enabled  codegraph serve --mcp\n'
  else
    printf 'No MCP servers configured.\n'
  fi
fi
exit 0
STUB
chmod +x "$STUB_BIN/agy"

# Every --antigravity invocation in this file goes through this helper, which
# appends whatever install.sh flags the caller passes after the log path, so
# none of them can ever escape to the real agy binary regardless of which
# flags a given scenario needs. (The external-skills section further down
# deploys Antigravity through --all instead; it runs under its own closed
# PATH, which holds this same agy stub.)
: > "$AGY_STUB_LOG"
run_antigravity() {
  local log="$1"
  shift
  # shellcheck disable=SC2031  # PATH is deliberately modified only inside this subshell; reading the outer PATH is intended
  ( export PATH="$STUB_BIN:$PATH" AGY_STUB_LOG; "$REPO/install.sh" --antigravity "$@" > "$log" 2>&1 )
}

# Synthetic fixture for generate_command_skills' duplicate-skill SKIP branch:
# stage a pre-existing symlink for commands/solution-survey.md to simulate
# the destination already being occupied by a same-named skill symlink.
mkdir -p "$T/synthetic-skill" "$T/gemini/config/skills"
ln -s "$T/synthetic-skill" "$T/gemini/config/skills/solution-survey"

run_antigravity "$T/log_ag1" --no-external

# repo skills are symlinked into agy's global skills dir
if test -L "$T/gemini/config/skills/deep-thinking"; then pass ag-skills-symlink; else bad ag-skills-symlink; fi

# commands become generated skills, with nested paths flattened
if test -f "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md"; then pass ag-cmd-skill; else bad ag-cmd-skill; fi
if sed -n '2p' "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" | grep -q 'GENERATED by install.sh'; then pass ag-cmd-skill-banner; else bad ag-cmd-skill-banner; fi
if grep -qx 'name: vf-trello-board-sprint-review' "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md"; then pass ag-cmd-skill-name; else bad ag-cmd-skill-name; fi

# generate_command_skills' SKIP branch: commands/solution-survey.md
# collides with the pre-existing symlink staged above, exercising Guard 1
# (destination is already a symlink) without mutating the repo.
if grep -qE 'SKIP.*solution-survey' "$T/log_ag1"; then pass ag-cmd-skill-skip-duplicate; else bad ag-cmd-skill-skip-duplicate; fi

# GEMINI.md carries CLAUDE.md + every rule, in full
if test -f "$T/gemini/GEMINI.md"; then pass ag-gemini-md; else bad ag-gemini-md; fi
if grep -q 'Think Before Coding' "$T/gemini/GEMINI.md"; then pass ag-gemini-claude; else bad ag-gemini-claude; fi
if grep -q 'Routing Table' "$T/gemini/GEMINI.md"; then pass ag-gemini-rules; else bad ag-gemini-rules; fi
if grep -q 'ripgrep' "$T/gemini/GEMINI.md"; then pass ag-gemini-search-rule; else bad ag-gemini-search-rule; fi

# subagents are generated in Antigravity's own frontmatter dialect
if test -f "$T/gemini/config/agents/docker-expert.md"; then pass ag-agent-file; else bad ag-agent-file; fi
if sed -n '2p' "$T/gemini/config/agents/docker-expert.md" | grep -q 'GENERATED by install.sh'; then pass ag-agent-banner; else bad ag-agent-banner; fi
if grep -qx 'subagent: true' "$T/gemini/config/agents/docker-expert.md"; then pass ag-agent-subagent; else bad ag-agent-subagent; fi
if grep -q '^tools:' "$T/gemini/config/agents/docker-expert.md"; then bad ag-agent-no-tools; else pass ag-agent-no-tools; fi

# idempotent second run
run_antigravity "$T/log_ag2" --no-external
if grep -q 'CONFLICT' "$T/log_ag2"; then bad ag-idempotent; else pass ag-idempotent; fi

# prune removes an orphaned generated command-skill, and only that
mkdir -p "$T/gemini/config/skills/gone-cmd"
printf -- '---\n# GENERATED by install.sh from commands/*.md - do not edit.\nname: gone-cmd\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/gone-cmd/SKILL.md"
run_antigravity "$T/log_ag3" --no-external
if test ! -d "$T/gemini/config/skills/gone-cmd"; then pass ag-cmd-prune; else bad ag-cmd-prune; fi
if test -L "$T/gemini/config/skills/deep-thinking"; then pass ag-prune-spares-symlinks; else bad ag-prune-spares-symlinks; fi

# prune does NOT remove a hand-authored skill dir (no banner)
mkdir -p "$T/gemini/config/skills/handmade"
printf -- '---\nname: handmade\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/handmade/SKILL.md"
run_antigravity "$T/log_ag4" --no-external
if test -f "$T/gemini/config/skills/handmade/SKILL.md"; then pass ag-keep-handmade; else bad ag-keep-handmade; fi

# Generate step does NOT overwrite a hand-authored command-skill that
# collides with a repo command's flattened name (mirrors the Codex
# keep-handmade-collision test above; vf-trello-board-sprint-review has no
# same-named repo skill, so this exercises the generic hand-authored guard
# rather than the repo-skill-duplicate SKIP path).
printf -- '---\nname: my-handwritten\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md"
