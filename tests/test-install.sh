#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
export CLAUDE_CONFIG_DIR="$T/claude"
export CODEX_HOME="$T/codex"
export AGENTS_HOME="$T/agents"
export GEMINI_HOME="$T/gemini"
# Default export so the agy stub's `${AGY_STUB_LOG:?}` expansion (further
# down) can never abort on an unset variable, even if some future call site
# forgets to (re)assign it before invoking the stub; scenario-specific blocks
# below reassign this to their own log path, which keeps the export attribute.
export AGY_STUB_LOG="$T/agy-stub.log"
# Test-only escape hatch: skip install-cli-tools.sh so this suite never
# triggers real sudo pacman/yay installs or rewrites the user's real ~/.zshrc.
export INSTALL_CLI_TOOLS=0

"$REPO/install.sh" --codex --no-external > "$T/log1" 2>&1

test -L "$AGENTS_HOME/skills/deep-thinking" && pass skills-symlink || bad skills-symlink
test -L "$CODEX_HOME/prompts/vf-trello-board-sprint-review.md" && pass cmd-flatten || bad cmd-flatten
test -f "$CODEX_HOME/config.toml" && pass config-seeded || bad config-seeded

# AGENTS.md is generated and contains CLAUDE.md + rules content
test -f "$CODEX_HOME/AGENTS.md" && pass agents-md-exists || bad agents-md-exists
grep -q 'Think Before Coding' "$CODEX_HOME/AGENTS.md" && pass agents-md-claude || bad agents-md-claude
grep -q 'Routing Table' "$CODEX_HOME/AGENTS.md" && pass agents-md-rules || bad agents-md-rules
grep -q 'ripgrep' "$CODEX_HOME/AGENTS.md" && pass agents-md-search-rule || bad agents-md-search-rule
grep -q 'CodeGraph' "$CODEX_HOME/AGENTS.md" && pass agents-md-codegraph || bad agents-md-codegraph

# Subagent TOMLs are generated
test -f "$CODEX_HOME/agents/docker-expert.toml" && pass toml-exists || bad toml-exists
head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh' && pass toml-banner || bad toml-banner

# Idempotent second run
"$REPO/install.sh" --codex --no-external > "$T/log2" 2>&1
grep -q 'CONFLICT' "$T/log2" && bad idempotent || pass idempotent

# Prune removes an orphaned generated TOML
printf '# GENERATED by install.sh from agents/*.md - do not edit.\nname = "gone"\n' > "$CODEX_HOME/agents/gone.toml"
"$REPO/install.sh" --codex --no-external > "$T/log3" 2>&1
test ! -f "$CODEX_HOME/agents/gone.toml" && pass prune || bad prune

# Prune does NOT remove a hand-authored TOML (no banner)
printf 'name = "handmade"\n' > "$CODEX_HOME/agents/handmade.toml"
"$REPO/install.sh" --codex --no-external > "$T/log4" 2>&1
test -f "$CODEX_HOME/agents/handmade.toml" && pass keep-handmade || bad keep-handmade

# Generate step does NOT overwrite a hand-authored TOML that collides with a
# repo agent name (docker-expert.toml collides with agents/docker-expert.md)
printf 'name = "my-handwritten"\n' > "$CODEX_HOME/agents/docker-expert.toml"
"$REPO/install.sh" --codex --no-external > "$T/log5" 2>&1
grep -q 'my-handwritten' "$CODEX_HOME/agents/docker-expert.toml" && pass keep-handmade-collision || bad keep-handmade-collision
head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh' && bad keep-handmade-collision-banner || pass keep-handmade-collision-banner

# ---- opencode ----
export OPENCODE_CONFIG_DIR="$T/opencode"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc1" 2>&1

# skills reuse the shared ~/.agents/skills dir
test -L "$AGENTS_HOME/skills/deep-thinking" && pass oc-skills || bad oc-skills
# commands flattened into opencode commands dir
test -L "$OPENCODE_CONFIG_DIR/commands/vf-trello-board-sprint-review.md" && pass oc-cmd || bad oc-cmd
# opencode.json symlinked
test -L "$OPENCODE_CONFIG_DIR/opencode.json" && pass oc-config || bad oc-config
# AGENTS.md generated with rules content
grep -q 'Routing Table' "$OPENCODE_CONFIG_DIR/AGENTS.md" && pass oc-agents-md || bad oc-agents-md
# subagent md generated; frontmatter fence on line 1, banner on line 2
test -f "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" && pass oc-agent-exists || bad oc-agent-exists
head -1 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -qx -- '---' && pass oc-agent-fm || bad oc-agent-fm
head -3 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -q 'GENERATED by install.sh' && pass oc-agent-banner || bad oc-agent-banner
# a read-only agent has write disabled
grep -q 'write: false' "$OPENCODE_CONFIG_DIR/agents/adversarial-thinker.md" && pass oc-agent-readonly || bad oc-agent-readonly

# idempotent second run
"$REPO/install.sh" --opencode --no-external > "$T/log_oc2" 2>&1
grep -q 'CONFLICT' "$T/log_oc2" && bad oc-idempotent || pass oc-idempotent

# prune orphaned generated agent md (banner on second line)
printf -- '---\n# GENERATED by install.sh from agents/*.md - do not edit.\ndescription: "gone"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/gone.md"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc3" 2>&1
test ! -f "$OPENCODE_CONFIG_DIR/agents/gone.md" && pass oc-prune || bad oc-prune

# keep hand-authored agent md (no banner)
printf -- '---\ndescription: "handmade"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/handmade.md"
"$REPO/install.sh" --opencode --no-external > "$T/log_oc4" 2>&1
test -f "$OPENCODE_CONFIG_DIR/agents/handmade.md" && pass oc-keep-handmade || bad oc-keep-handmade

# ---- codegraph MCP registration (Claude Code): real behavior, not string match ----
# Stub `claude` logs every invocation ($* per call, one line) and lets
# `mcp get codegraph`'s exit code be controlled via CLAUDE_MCP_GET_EXIT, so
# both branches of register_codegraph_mcp can be exercised without a real
# claude CLI or network access.
STUB_BIN="$T/stub-bin"
mkdir -p "$STUB_BIN"
cat > "$STUB_BIN/claude" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${CLAUDE_STUB_LOG:?}"
if [ "${1:-}" = "mcp" ] && [ "${2:-}" = "get" ]; then
  exit "${CLAUDE_MCP_GET_EXIT:-0}"
fi
exit 0
STUB
chmod +x "$STUB_BIN/claude"

# Scenario A: codegraph not yet registered (mcp get exits 1) -> install.sh
# must call `claude mcp add codegraph --scope user -- codegraph serve --mcp`.
export CLAUDE_CONFIG_DIR="$T/claude-notreg"
CLAUDE_STUB_LOG="$T/claude-stub-notreg.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=1; "$REPO/install.sh" --claude --no-external > "$T/log_claude_notreg" 2>&1 )
grep -qxF 'mcp add codegraph --scope user -- codegraph serve --mcp' "$CLAUDE_STUB_LOG" && pass codegraph-mcp-registers-when-absent || bad codegraph-mcp-registers-when-absent

# Scenario B: codegraph already registered (mcp get exits 0) -> install.sh
# must NOT call `claude mcp add` at all.
export CLAUDE_CONFIG_DIR="$T/claude-reg"
CLAUDE_STUB_LOG="$T/claude-stub-reg.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude --no-external > "$T/log_claude_reg" 2>&1 )
grep -q '^mcp add' "$CLAUDE_STUB_LOG" && bad codegraph-mcp-skips-when-registered || pass codegraph-mcp-skips-when-registered

# ---- Antigravity CLI ----
# Stub `agy` before any --antigravity run: once register_codegraph_mcp_antigravity
# exists, an unstubbed run would reach the real agy on this machine and mutate
# the developer's live MCP config. AGY_MCP_HAS_CODEGRAPH switches the two
# branches of that function; the log lets later scenarios assert on calls.
cat > "$STUB_BIN/agy" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${AGY_STUB_LOG:?}"
if [ "${1:-}" = "mcp" ] && [ "${2:-}" = "list" ]; then
  if [ "${AGY_MCP_HAS_CODEGRAPH:-0}" = "1" ]; then
    printf 'NAME        TYPE   STATUS   COMMAND/URL\n'
    printf 'codegraph   stdio  enabled  codegraph serve --mcp\n'
  else
    printf 'No MCP servers configured.\n'
  fi
fi
exit 0
STUB
chmod +x "$STUB_BIN/agy"

# Every --antigravity invocation in this file goes through this helper, which
# appends whatever install.sh flags the caller passes after the log path, so
# none of them can ever escape to the real agy binary regardless of which
# flags a given scenario needs (e.g. the external-skill bridge test below
# intentionally omits --no-external).
: > "$AGY_STUB_LOG"
run_antigravity() {
  local log="$1"
  shift
  ( export PATH="$STUB_BIN:$PATH" AGY_STUB_LOG; "$REPO/install.sh" --antigravity "$@" > "$log" 2>&1 )
}

# Synthetic fixture for generate_command_skills' duplicate-skill SKIP branch:
# stage a pre-existing symlink for commands/solution-survey.md to simulate
# the destination already being occupied by a same-named skill symlink.
mkdir -p "$T/synthetic-skill" "$T/gemini/config/skills"
ln -s "$T/synthetic-skill" "$T/gemini/config/skills/solution-survey"

run_antigravity "$T/log_ag1" --no-external

# repo skills are symlinked into agy's global skills dir
test -L "$T/gemini/config/skills/deep-thinking" && pass ag-skills-symlink || bad ag-skills-symlink

# commands become generated skills, with nested paths flattened
test -f "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" && pass ag-cmd-skill || bad ag-cmd-skill
sed -n '2p' "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" | grep -q 'GENERATED by install.sh' && pass ag-cmd-skill-banner || bad ag-cmd-skill-banner
grep -qx 'name: vf-trello-board-sprint-review' "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" && pass ag-cmd-skill-name || bad ag-cmd-skill-name

# generate_command_skills' SKIP branch: commands/solution-survey.md
# collides with the pre-existing symlink staged above, exercising Guard 1
# (destination is already a symlink) without mutating the repo.
grep -qE 'SKIP.*solution-survey' "$T/log_ag1" && pass ag-cmd-skill-skip-duplicate || bad ag-cmd-skill-skip-duplicate

# GEMINI.md carries CLAUDE.md + every rule, in full
test -f "$T/gemini/GEMINI.md" && pass ag-gemini-md || bad ag-gemini-md
grep -q 'Think Before Coding' "$T/gemini/GEMINI.md" && pass ag-gemini-claude || bad ag-gemini-claude
grep -q 'Routing Table' "$T/gemini/GEMINI.md" && pass ag-gemini-rules || bad ag-gemini-rules
grep -q 'ripgrep' "$T/gemini/GEMINI.md" && pass ag-gemini-search-rule || bad ag-gemini-search-rule

# subagents are generated in Antigravity's own frontmatter dialect
test -f "$T/gemini/config/agents/docker-expert.md" && pass ag-agent-file || bad ag-agent-file
sed -n '2p' "$T/gemini/config/agents/docker-expert.md" | grep -q 'GENERATED by install.sh' && pass ag-agent-banner || bad ag-agent-banner
grep -qx 'subagent: true' "$T/gemini/config/agents/docker-expert.md" && pass ag-agent-subagent || bad ag-agent-subagent
grep -q '^tools:' "$T/gemini/config/agents/docker-expert.md" && bad ag-agent-no-tools || pass ag-agent-no-tools

# idempotent second run
run_antigravity "$T/log_ag2" --no-external
grep -q 'CONFLICT' "$T/log_ag2" && bad ag-idempotent || pass ag-idempotent

# prune removes an orphaned generated command-skill, and only that
mkdir -p "$T/gemini/config/skills/gone-cmd"
printf -- '---\n# GENERATED by install.sh from commands/*.md - do not edit.\nname: gone-cmd\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/gone-cmd/SKILL.md"
run_antigravity "$T/log_ag3" --no-external
test ! -d "$T/gemini/config/skills/gone-cmd" && pass ag-cmd-prune || bad ag-cmd-prune
test -L "$T/gemini/config/skills/deep-thinking" && pass ag-prune-spares-symlinks || bad ag-prune-spares-symlinks

# prune does NOT remove a hand-authored skill dir (no banner)
mkdir -p "$T/gemini/config/skills/handmade"
printf -- '---\nname: handmade\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/handmade/SKILL.md"
run_antigravity "$T/log_ag4" --no-external
test -f "$T/gemini/config/skills/handmade/SKILL.md" && pass ag-keep-handmade || bad ag-keep-handmade

# Generate step does NOT overwrite a hand-authored command-skill that
# collides with a repo command's flattened name (mirrors the Codex
# keep-handmade-collision test above; vf-trello-board-sprint-review has no
# same-named repo skill, so this exercises the generic hand-authored guard
# rather than the repo-skill-duplicate SKIP path).
printf -- '---\nname: my-handwritten\ndescription: "x"\n---\nbody\n' > "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md"
run_antigravity "$T/log_ag5" --no-external
grep -q 'my-handwritten' "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" && pass ag-keep-handmade-collision || bad ag-keep-handmade-collision
head -3 "$T/gemini/config/skills/vf-trello-board-sprint-review/SKILL.md" | grep -q 'GENERATED by install.sh' && bad ag-keep-handmade-collision-banner || pass ag-keep-handmade-collision-banner

# GEMINI.md overwrite guard: a hand-authored file with no banner must be left
# alone. Unlike Codex/opencode's AGENTS.md (repo-only paths), GEMINI.md is
# also the path Antigravity's own Customizations panel writes to when a user
# clicks "+ Global", so real user content can already be sitting there before
# install.sh ever runs. Uses a fresh GEMINI_HOME so the pre-seeded content
# here can't collide with the generated GEMINI.md already produced above.
GEMINI_CONFLICT_HOME="$T/gemini-conflict"
mkdir -p "$GEMINI_CONFLICT_HOME"
printf 'my hand-authored global rules\n' > "$GEMINI_CONFLICT_HOME/GEMINI.md"
export GEMINI_HOME="$GEMINI_CONFLICT_HOME"
run_antigravity "$T/log_ag_gemini_conflict" --no-external
grep -qxF 'my hand-authored global rules' "$GEMINI_CONFLICT_HOME/GEMINI.md" && pass ag-gemini-md-conflict-preserved || bad ag-gemini-md-conflict-preserved
grep -qF "CONFLICT ${GEMINI_CONFLICT_HOME}/GEMINI.md" "$T/log_ag_gemini_conflict" && pass ag-gemini-md-conflict-logged || bad ag-gemini-md-conflict-logged
export GEMINI_HOME="$T/gemini"

# ---- codegraph MCP registration (Antigravity): real behavior, not string match ----
# Scenario A: codegraph absent -> install.sh must register it.
export GEMINI_HOME="$T/gemini-mcp-notreg"
AGY_STUB_LOG="$T/agy-stub-notreg.log"
: > "$AGY_STUB_LOG"
export AGY_MCP_HAS_CODEGRAPH=0
run_antigravity "$T/log_ag_mcp1" --no-external
unset AGY_MCP_HAS_CODEGRAPH
grep -qxF 'mcp add codegraph -- codegraph serve --mcp' "$AGY_STUB_LOG" && pass ag-mcp-registers-when-absent || bad ag-mcp-registers-when-absent

# Scenario B: codegraph already listed -> install.sh must NOT call `agy mcp add`.
export GEMINI_HOME="$T/gemini-mcp-reg"
AGY_STUB_LOG="$T/agy-stub-reg.log"
: > "$AGY_STUB_LOG"
export AGY_MCP_HAS_CODEGRAPH=1
run_antigravity "$T/log_ag_mcp2" --no-external
unset AGY_MCP_HAS_CODEGRAPH
grep -q '^mcp add' "$AGY_STUB_LOG" && bad ag-mcp-skips-when-registered || pass ag-mcp-skips-when-registered

# The external-skill bridge must symlink agy-scoped external skills into the
# dir agy actually reads, and must obey --no-external like the other three
# platforms. This has to exercise install_external_skills for real (no
# --no-external), which also un-gates install_openspec's unconditional
# end-of-script `npm install --global` — so PATH gets npx and npm stubs on
# top of the existing claude/agy ones: npx fabricates the on-disk result
# `skills add` would leave under GEMINI_HOME/antigravity-cli/skills for the
# manifest's one active entry (herdrdev/herdr@herdr), and npm is a pure no-op
# so install_openspec can never reach the real npm on this machine.
cat > "$STUB_BIN/npx" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
# Simulate `npx --yes skills add <entry> -g -a <agent_id> -y`: install.sh only
# checks the exit code, so this only needs to fabricate the skill directory
# the real `skills` CLI would have created, without touching the network.
if [ "${2:-}" = "skills" ] && [ "${3:-}" = "add" ]; then
  entry="$4"
  skill_name="${entry##*@}"
  mkdir -p "${GEMINI_HOME:?}/antigravity-cli/skills/${skill_name}"
  printf -- '---\nname: %s\ndescription: "x"\n---\nbody\n' "$skill_name" \
    > "${GEMINI_HOME}/antigravity-cli/skills/${skill_name}/SKILL.md"
fi
exit 0
STUB
chmod +x "$STUB_BIN/npx"
cat > "$STUB_BIN/npm" <<'STUB'
#!/usr/bin/env bash
# install_openspec's `npm install --global` is un-gated once --no-external is
# omitted; stubbed here as a pure no-op so it never reaches the real npm.
exit 0
STUB
chmod +x "$STUB_BIN/npm"

export GEMINI_HOME="$T/gemini-bridge"
AGY_STUB_LOG="$T/agy-stub-bridge.log"
: > "$AGY_STUB_LOG"
run_antigravity "$T/log_ag_bridge"
test -L "$T/gemini-bridge/config/skills/herdr" && pass ag-external-bridge || bad ag-external-bridge

# --all must include antigravity
grep -qE '^\s*--all\).*want_antigravity=1' "$REPO/install.sh" && pass ag-in-all || bad ag-in-all

# ---- INSTALL_CLI_TOOLS=0 must actually skip install-cli-tools.sh, not just avoid crashing ----
# install-cli-tools.sh's own startup message is a marker: if the bootstrap
# step never ran, that message can never appear in install.sh's captured
# output (INSTALL_CLI_TOOLS=0 is exported for this whole suite, so any prior
# log works as the sample; log_claude_reg from scenario B above is used).
grep -qF '開始安裝 CLI 工具' "$T/log_claude_reg" && bad install-cli-tools-actually-skipped || pass install-cli-tools-actually-skipped

# ---- regression guard: the retired --claude-personal mechanism must never
# reappear in install.sh's source. clauth's per-run CLAUDE_CONFIG_DIR mirror
# (see the CLAUDE_CONFIG_DIR warning further up in install.sh) now covers
# both reasons that mechanism used to exist - a second, isolated credentials
# dir and cross-subscription session sharing - so there is no live code path
# that should ever reintroduce these identifiers. install-cli-tools.sh has
# its own guard for the parallel ".claude-personal" directory string in the
# alias block (tests/test-cli-aliases.sh); this one is install.sh's, since a
# merge conflict or a copy-pasted fragment from an old branch could drop
# either piece back in independently of the other. ----
for identifier in '--claude-personal' CLAUDE_PERSONAL_CONFIG_DIR deploy_claude_personal; do
  # -e (not a bare pattern argument) is required here: "--claude-personal"
  # starts with "--", so grep would otherwise parse it as an unrecognized
  # option rather than the search pattern, print a usage error to stderr,
  # exit non-zero, and fall into the `|| pass` branch below for the wrong
  # reason - a false PASS that never actually searched for anything.
  # shellcheck disable=SC2015  # pass/bad never fail, so && / || is safe here (repo-wide test idiom)
  grep -qF -e "$identifier" "$REPO/install.sh" && bad "no-${identifier#--}-left-in-install-sh" || pass "no-${identifier#--}-left-in-install-sh"
done

# ---- external skills manifest ----
# The herdr entry MUST pin the skill name: herdrdev/herdr ships four skills
# (herdr, herdr-pre-release-audit, herdr-throwaway-repro, triage) and an
# unpinned entry would install all four into every platform's global dir.
MANIFEST="$REPO/external-skills.txt"
grep -qxF 'herdrdev/herdr@herdr' "$MANIFEST" && pass herdr-skill-entry || bad herdr-skill-entry
grep -qE '^herdrdev/herdr$' "$MANIFEST" && bad herdr-skill-pinned || pass herdr-skill-pinned

exit $fail
