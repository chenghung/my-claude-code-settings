#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
export CLAUDE_CONFIG_DIR="$T/claude"
export CODEX_HOME="$T/codex"
export AGENTS_HOME="$T/agents"
# Test-only escape hatch: skip install-cli-tools.sh so this suite never
# triggers real sudo pacman/yay installs or rewrites the user's real ~/.zshrc.
export INSTALL_CLI_TOOLS=0

"$REPO/install.sh" --codex > "$T/log1" 2>&1

test -L "$AGENTS_HOME/skills/deep-thinking" && pass skills-symlink || bad skills-symlink
test -L "$CODEX_HOME/prompts/vf-trello-board-sprint-review.md" && pass cmd-flatten || bad cmd-flatten
test -f "$CODEX_HOME/config.toml" && pass config-seeded || bad config-seeded

# AGENTS.md is generated and contains CLAUDE.md + rules content
test -f "$CODEX_HOME/AGENTS.md" && pass agents-md-exists || bad agents-md-exists
grep -q 'Think Before Coding' "$CODEX_HOME/AGENTS.md" && pass agents-md-claude || bad agents-md-claude
grep -q 'Routing Table' "$CODEX_HOME/AGENTS.md" && pass agents-md-rules || bad agents-md-rules
grep -q 'ripgrep' "$CODEX_HOME/AGENTS.md" && pass agents-md-search-rule || bad agents-md-search-rule
grep -q 'CodeGraph' "$CODEX_HOME/AGENTS.md" && pass agents-md-codegraph || bad agents-md-codegraph

# Subagent TOMLs are generated
test -f "$CODEX_HOME/agents/docker-expert.toml" && pass toml-exists || bad toml-exists
head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh' && pass toml-banner || bad toml-banner

# Idempotent second run
"$REPO/install.sh" --codex > "$T/log2" 2>&1
grep -q 'CONFLICT' "$T/log2" && bad idempotent || pass idempotent

# Prune removes an orphaned generated TOML
printf '# GENERATED by install.sh from agents/*.md - do not edit.\nname = "gone"\n' > "$CODEX_HOME/agents/gone.toml"
"$REPO/install.sh" --codex > "$T/log3" 2>&1
test ! -f "$CODEX_HOME/agents/gone.toml" && pass prune || bad prune

# Prune does NOT remove a hand-authored TOML (no banner)
printf 'name = "handmade"\n' > "$CODEX_HOME/agents/handmade.toml"
"$REPO/install.sh" --codex > "$T/log4" 2>&1
test -f "$CODEX_HOME/agents/handmade.toml" && pass keep-handmade || bad keep-handmade

# Generate step does NOT overwrite a hand-authored TOML that collides with a
# repo agent name (docker-expert.toml collides with agents/docker-expert.md)
printf 'name = "my-handwritten"\n' > "$CODEX_HOME/agents/docker-expert.toml"
"$REPO/install.sh" --codex > "$T/log5" 2>&1
grep -q 'my-handwritten' "$CODEX_HOME/agents/docker-expert.toml" && pass keep-handmade-collision || bad keep-handmade-collision
head -1 "$CODEX_HOME/agents/docker-expert.toml" | grep -q 'GENERATED by install.sh' && bad keep-handmade-collision-banner || pass keep-handmade-collision-banner

# ---- opencode ----
export OPENCODE_CONFIG_DIR="$T/opencode"
"$REPO/install.sh" --opencode > "$T/log_oc1" 2>&1

# skills reuse the shared ~/.agents/skills dir
test -L "$AGENTS_HOME/skills/deep-thinking" && pass oc-skills || bad oc-skills
# commands flattened into opencode commands dir
test -L "$OPENCODE_CONFIG_DIR/commands/vf-trello-board-sprint-review.md" && pass oc-cmd || bad oc-cmd
# opencode.json symlinked
test -L "$OPENCODE_CONFIG_DIR/opencode.json" && pass oc-config || bad oc-config
# AGENTS.md generated with rules content
grep -q 'Routing Table' "$OPENCODE_CONFIG_DIR/AGENTS.md" && pass oc-agents-md || bad oc-agents-md
# subagent md generated; frontmatter fence on line 1, banner on line 2
test -f "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" && pass oc-agent-exists || bad oc-agent-exists
head -1 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -qx -- '---' && pass oc-agent-fm || bad oc-agent-fm
head -3 "$OPENCODE_CONFIG_DIR/agents/docker-expert.md" | grep -q 'GENERATED by install.sh' && pass oc-agent-banner || bad oc-agent-banner
# a read-only agent has write disabled
grep -q 'write: false' "$OPENCODE_CONFIG_DIR/agents/adversarial-thinker.md" && pass oc-agent-readonly || bad oc-agent-readonly

# idempotent second run
"$REPO/install.sh" --opencode > "$T/log_oc2" 2>&1
grep -q 'CONFLICT' "$T/log_oc2" && bad oc-idempotent || pass oc-idempotent

# prune orphaned generated agent md (banner on second line)
printf -- '---\n# GENERATED by install.sh from agents/*.md - do not edit.\ndescription: "gone"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/gone.md"
"$REPO/install.sh" --opencode > "$T/log_oc3" 2>&1
test ! -f "$OPENCODE_CONFIG_DIR/agents/gone.md" && pass oc-prune || bad oc-prune

# keep hand-authored agent md (no banner)
printf -- '---\ndescription: "handmade"\nmode: subagent\n---\nx\n' > "$OPENCODE_CONFIG_DIR/agents/handmade.md"
"$REPO/install.sh" --opencode > "$T/log_oc4" 2>&1
test -f "$OPENCODE_CONFIG_DIR/agents/handmade.md" && pass oc-keep-handmade || bad oc-keep-handmade

# ---- codegraph MCP registration (Claude Code): real behavior, not string match ----
# Stub `claude` logs every invocation ($* per call, one line) and lets
# `mcp get codegraph`'s exit code be controlled via CLAUDE_MCP_GET_EXIT, so
# both branches of register_codegraph_mcp can be exercised without a real
# claude CLI or network access.
STUB_BIN="$T/stub-bin"
mkdir -p "$STUB_BIN"
cat > "$STUB_BIN/claude" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${CLAUDE_STUB_LOG:?}"
if [ "${1:-}" = "mcp" ] && [ "${2:-}" = "get" ]; then
  exit "${CLAUDE_MCP_GET_EXIT:-0}"
fi
exit 0
STUB
chmod +x "$STUB_BIN/claude"

# Scenario A: codegraph not yet registered (mcp get exits 1) -> install.sh
# must call `claude mcp add codegraph --scope user -- codegraph serve --mcp`.
export CLAUDE_CONFIG_DIR="$T/claude-notreg"
CLAUDE_STUB_LOG="$T/claude-stub-notreg.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=1; "$REPO/install.sh" --claude --no-external > "$T/log_claude_notreg" 2>&1 )
grep -qxF 'mcp add codegraph --scope user -- codegraph serve --mcp' "$CLAUDE_STUB_LOG" && pass codegraph-mcp-registers-when-absent || bad codegraph-mcp-registers-when-absent

# Scenario B: codegraph already registered (mcp get exits 0) -> install.sh
# must NOT call `claude mcp add` at all.
export CLAUDE_CONFIG_DIR="$T/claude-reg"
CLAUDE_STUB_LOG="$T/claude-stub-reg.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude --no-external > "$T/log_claude_reg" 2>&1 )
grep -q '^mcp add' "$CLAUDE_STUB_LOG" && bad codegraph-mcp-skips-when-registered || pass codegraph-mcp-skips-when-registered

# ---- INSTALL_CLI_TOOLS=0 must actually skip install-cli-tools.sh, not just avoid crashing ----
# install-cli-tools.sh's own startup message is a marker: if the bootstrap
# step never ran, that message can never appear in install.sh's captured
# output (INSTALL_CLI_TOOLS=0 is exported for this whole suite, so any prior
# log works as the sample; log_claude_reg from scenario B above is used).
grep -qF '開始安裝 CLI 工具' "$T/log_claude_reg" && bad install-cli-tools-actually-skipped || pass install-cli-tools-actually-skipped

# ---- guard: deploy_claude_personal aborts when CLAUDE_CONFIG_DIR and
# CLAUDE_PERSONAL_CONFIG_DIR resolve to the same directory. This is what
# happens if install.sh runs inside a Claude Code session started by the
# personal-subscription launcher, which exports CLAUDE_CONFIG_DIR into the
# session (every child process inherits it) so it collides with
# CLAUDE_PERSONAL_CONFIG_DIR's own default. Without the guard, link_one
# would link every session-state path to itself.
SELFREF_DIR="$T/claude-selfref"
mkdir -p "$SELFREF_DIR"
export CLAUDE_CONFIG_DIR="$SELFREF_DIR"
export CLAUDE_PERSONAL_CONFIG_DIR="$SELFREF_DIR"
CLAUDE_STUB_LOG="$T/claude-stub-selfref.log"
: > "$CLAUDE_STUB_LOG"
selfref_status=0
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude-personal --no-external > "$T/log_selfref" 2>&1 ) || selfref_status=$?

[ "$selfref_status" -ne 0 ] && pass selfref-guard-aborts || bad selfref-guard-aborts
grep -qF 'CLAUDE_CONFIG_DIR and CLAUDE_PERSONAL_CONFIG_DIR both resolve to' "$T/log_selfref" && pass selfref-guard-message || bad selfref-guard-message
[ -z "$(ls -A "$SELFREF_DIR")" ] && pass selfref-guard-no-links || bad selfref-guard-no-links

# ---- --claude-personal deploys the repo payload into the personal config
# dir when the two dirs differ. This block also doubles as the "normal case
# unaffected" regression check for the equality guard above. ----
export CLAUDE_CONFIG_DIR="$T/claude-default"
export CLAUDE_PERSONAL_CONFIG_DIR="$T/claude-personal"
CLAUDE_STUB_LOG="$T/claude-stub-personal.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude-personal --no-external > "$T/log_personal" 2>&1 )

grep -q 'No platform selected' "$T/log_personal" && bad personal-flag-counts-as-platform || pass personal-flag-counts-as-platform
test -L "$CLAUDE_PERSONAL_CONFIG_DIR/agents" && pass personal-agents-symlink || bad personal-agents-symlink
test -L "$CLAUDE_PERSONAL_CONFIG_DIR/settings.json" && pass personal-settings-symlink || bad personal-settings-symlink
test -L "$CLAUDE_PERSONAL_CONFIG_DIR/skills/deep-thinking" && pass personal-skills-symlink || bad personal-skills-symlink
# Scope note: this only proves repo-owned config (agents/, rules/, etc.) was
# not deployed into the default dir by --claude-personal. It does NOT mean
# the default dir stays untouched overall — the session-state dirs checked
# below ARE created there on purpose, since link_one's targets must exist.
test ! -e "$CLAUDE_CONFIG_DIR/agents" && pass personal-flag-leaves-default-alone || bad personal-flag-leaves-default-alone

# ---- the four session-state dirs are symlinked at the DEFAULT config dir ----
for d in projects session-env file-history tasks; do
  test -L "$CLAUDE_PERSONAL_CONFIG_DIR/$d" && pass "personal-$d-is-symlink" || bad "personal-$d-is-symlink"
  [ "$(readlink "$CLAUDE_PERSONAL_CONFIG_DIR/$d")" = "$CLAUDE_CONFIG_DIR/$d" ] && pass "personal-$d-target" || bad "personal-$d-target"
  # Self-referential link would silently defeat session sharing entirely.
  # -L is required first: without it, a missing link makes readlink print
  # "", which trivially differs from the personal path and would make this
  # assertion pass even though the link was never created at all.
  [ -L "$CLAUDE_PERSONAL_CONFIG_DIR/$d" ] && [ "$(readlink "$CLAUDE_PERSONAL_CONFIG_DIR/$d")" != "$CLAUDE_PERSONAL_CONFIG_DIR/$d" ] && pass "personal-$d-not-self" || bad "personal-$d-not-self"
  test -d "$CLAUDE_CONFIG_DIR/$d" && pass "default-$d-dir-ensured" || bad "default-$d-dir-ensured"
done

# Idempotent re-run must not report conflicts.
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude-personal --no-external > "$T/log_personal2" 2>&1 )
grep -q 'CONFLICT' "$T/log_personal2" && bad personal-idempotent || pass personal-idempotent

# Non-destructive: a real, populated dir sitting at each of the four link
# paths must be reported as a conflict and left byte-for-byte intact. These
# dirs hold the user's actual conversation history, so corruption here is
# permanent data loss — each gets a non-empty file plus a nested
# subdirectory, and content is diffed (not just existence-checked) after the
# run, since a same-name file surviving with its content silently wiped
# would pass an existence check but must fail this one.
export CLAUDE_PERSONAL_CONFIG_DIR="$T/claude-personal-conflict"
CONFLICT_SNAPSHOT="$T/claude-personal-conflict-snapshot"
for d in projects session-env file-history tasks; do
  mkdir -p "$CLAUDE_PERSONAL_CONFIG_DIR/$d/nested"
  printf 'precious-%s-marker\n' "$d" > "$CLAUDE_PERSONAL_CONFIG_DIR/$d/marker.txt"
  printf 'precious-%s-nested\n' "$d" > "$CLAUDE_PERSONAL_CONFIG_DIR/$d/nested/nested-file.txt"
done
mkdir -p "$CONFLICT_SNAPSHOT"
cp -r "$CLAUDE_PERSONAL_CONFIG_DIR/." "$CONFLICT_SNAPSHOT/"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --claude-personal --no-external > "$T/log_personal3" 2>&1 )
for d in projects session-env file-history tasks; do
  grep -qF "CONFLICT ${CLAUDE_PERSONAL_CONFIG_DIR}/${d}" "$T/log_personal3" && pass "personal-$d-conflict-reported" || bad "personal-$d-conflict-reported"
  diff -r "$CONFLICT_SNAPSHOT/$d" "$CLAUDE_PERSONAL_CONFIG_DIR/$d" > /dev/null 2>&1 && pass "personal-$d-not-destroyed" || bad "personal-$d-not-destroyed"
done

# ---- --all covers BOTH Claude Code config dirs ----
# The default and personal dirs are two permanent targets on this machine, so
# "all" must mean both. Before this was wired up, --all silently skipped the
# personal dir and it went stale without any signal. All four payload
# categories are asserted in both dirs: agents/ and hooks/ are whole-dir
# symlinks (link_directory), skills/ and commands/ are per-item symlinks
# (link_items) — a regression in either mode would strand one category.
export CLAUDE_CONFIG_DIR="$T/all-default"
export CLAUDE_PERSONAL_CONFIG_DIR="$T/all-personal"
export CODEX_HOME="$T/all-codex"
export OPENCODE_CONFIG_DIR="$T/all-opencode"
CLAUDE_STUB_LOG="$T/claude-stub-all.log"
: > "$CLAUDE_STUB_LOG"
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --all --no-external > "$T/log_all" 2>&1 )

for label in default:"$CLAUDE_CONFIG_DIR" personal:"$CLAUDE_PERSONAL_CONFIG_DIR"; do
  name="${label%%:*}"
  dir="${label#*:}"
  test -L "$dir/agents" && pass "all-$name-agents" || bad "all-$name-agents"
  test -L "$dir/hooks" && pass "all-$name-hooks" || bad "all-$name-hooks"
  test -L "$dir/rules" && pass "all-$name-rules" || bad "all-$name-rules"
  test -L "$dir/skills/deep-thinking" && pass "all-$name-skills" || bad "all-$name-skills"
  test -L "$dir/commands/solution-survey.md" && pass "all-$name-commands" || bad "all-$name-commands"
  test -L "$dir/settings.json" && pass "all-$name-settings" || bad "all-$name-settings"
  test -L "$dir/CLAUDE.md" && pass "all-$name-claude-md" || bad "all-$name-claude-md"
done

# --all must still reach the other two platforms.
test -L "$CODEX_HOME/prompts/solution-survey.md" && pass all-codex-prompts || bad all-codex-prompts
test -L "$OPENCODE_CONFIG_DIR/commands/solution-survey.md" && pass all-opencode-commands || bad all-opencode-commands

# ---- the equality guard is pre-flight: it aborts before ANY deploy ----
# The guard used to live inside deploy_claude_personal, which runs last. Once
# --all implies --claude-personal, that placement would deploy three platforms
# and only then exit 1, leaving a half-finished install and no summary. The
# check must therefore run before the first deploy, so the run is all-or-
# nothing: nothing is written anywhere, and the operator is told to re-run
# from a plain shell.
FAILFAST_DIR="$T/failfast-selfref"
mkdir -p "$FAILFAST_DIR"
export CLAUDE_CONFIG_DIR="$FAILFAST_DIR"
export CLAUDE_PERSONAL_CONFIG_DIR="$FAILFAST_DIR"
export CODEX_HOME="$T/failfast-codex"
export OPENCODE_CONFIG_DIR="$T/failfast-opencode"
export AGENTS_HOME="$T/failfast-agents"
CLAUDE_STUB_LOG="$T/claude-stub-failfast.log"
: > "$CLAUDE_STUB_LOG"
failfast_status=0
( export PATH="$STUB_BIN:$PATH" CLAUDE_STUB_LOG CLAUDE_MCP_GET_EXIT=0; "$REPO/install.sh" --all --no-external > "$T/log_failfast" 2>&1 ) || failfast_status=$?

[ "$failfast_status" -ne 0 ] && pass failfast-aborts || bad failfast-aborts
grep -qF 'CLAUDE_CONFIG_DIR and CLAUDE_PERSONAL_CONFIG_DIR both resolve to' "$T/log_failfast" && pass failfast-message || bad failfast-message
[ -z "$(ls -A "$FAILFAST_DIR")" ] && pass failfast-claude-untouched || bad failfast-claude-untouched
test ! -e "$CODEX_HOME" && pass failfast-codex-untouched || bad failfast-codex-untouched
test ! -e "$OPENCODE_CONFIG_DIR" && pass failfast-opencode-untouched || bad failfast-opencode-untouched
test ! -e "$AGENTS_HOME" && pass failfast-agents-untouched || bad failfast-agents-untouched

exit $fail
