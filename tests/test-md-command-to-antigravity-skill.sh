#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-command-to-antigravity-skill.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: a normal command file -> SKILL.md with the name supplied by the caller
cat > "$TMP/cmd.md" <<'MD'
---
description: Analyze the board and generate a sprint review report.
---

# Sprint Review

Step one.
MD
out="$(python3 "$CONVERT" "$TMP/cmd.md" vf-trello-board-sprint-review)"
if printf '%s\n' "$out" | head -1 | grep -qx -- '---'; then pass fm-first-line; else bad fm-first-line; fi
if printf '%s\n' "$out" | sed -n '2p' | grep -q '^# GENERATED by install.sh'; then pass banner-line2; else bad banner-line2; fi
if printf '%s\n' "$out" | sed -n '2p' | grep -q 'from commands/'; then pass banner-source; else bad banner-source; fi
if printf '%s\n' "$out" | grep -qx 'name: vf-trello-board-sprint-review'; then pass name-from-arg; else bad name-from-arg; fi
if printf '%s\n' "$out" | grep -q '^description: "Analyze the board'; then pass desc; else bad desc; fi
if printf '%s\n' "$out" | grep -q '^# Sprint Review'; then pass body-heading; else bad body-heading; fi
if printf '%s\n' "$out" | grep -q 'Step one.'; then pass body; else bad body; fi

# Case 2: description with a colon and double quotes -> escaped
cat > "$TMP/q.md" <<'MD'
---
description: run when: it says "go" to you
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/q.md" q-cmd)"
if printf '%s\n' "$out" | grep -q 'description: "run when: it says \\"go\\" to you"'; then pass esc-desc; else bad esc-desc; fi

# Case 3: missing frontmatter -> exit 1
printf 'no frontmatter\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" x >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 4: missing description -> exit 1
printf -- '---\nfoo: bar\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" x >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 5: wrong argument count -> exit 2
if python3 "$CONVERT" "$TMP/cmd.md" >/dev/null 2>&1; then bad argc; else pass argc; fi

# Case 6: the repo's own command files all convert cleanly
for f in "$REPO"/commands/*.md "$REPO"/commands/*/*.md; do
  [ -e "$f" ] || continue
  if python3 "$CONVERT" "$f" probe >/dev/null 2>&1; then
    pass "real-$(basename "$f" .md)"
  else
    bad "real-$(basename "$f" .md)"
  fi
done

exit $fail
