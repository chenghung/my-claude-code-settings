#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-agent-to-antigravity.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: a normal agent -> full frontmatter, no tools field
cat > "$TMP/basic.md" <<'MD'
---
name: basic-agent
description: use this agent when reviewing things
tools: Read, Grep
model: sonnet
---
You are a basic agent.
MD
out="$(python3 "$CONVERT" "$TMP/basic.md")"
if printf '%s\n' "$out" | head -1 | grep -qx -- '---'; then pass fm-first-line; else bad fm-first-line; fi
if printf '%s\n' "$out" | sed -n '2p' | grep -q '^# GENERATED by install.sh'; then pass banner-line2; else bad banner-line2; fi
if printf '%s\n' "$out" | grep -qx 'name: basic-agent'; then pass name; else bad name; fi
if printf '%s\n' "$out" | grep -qx 'mainAgent: false'; then pass main-agent; else bad main-agent; fi
if printf '%s\n' "$out" | grep -qx 'subagent: true'; then pass subagent; else bad subagent; fi
if printf '%s\n' "$out" | grep -qx 'model: pro'; then pass model-sonnet; else bad model-sonnet; fi
if printf '%s\n' "$out" | grep -q '^tools:'; then bad no-tools; else pass no-tools; fi
if printf '%s\n' "$out" | grep -q 'You are a basic agent.'; then pass body; else bad body; fi

# Case 2: haiku -> flash
cat > "$TMP/h.md" <<'MD'
---
name: h-agent
description: cheap agent
model: haiku
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/h.md")"
if printf '%s\n' "$out" | grep -qx 'model: flash'; then pass model-haiku; else bad model-haiku; fi

# Case 3: name absent -> derived from the filename stem
cat > "$TMP/derived-name.md" <<'MD'
---
description: no name field at all
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/derived-name.md")"
if printf '%s\n' "$out" | grep -qx 'name: derived-name'; then pass name-from-filename; else bad name-from-filename; fi

# Case 4: description with a colon and double quotes -> escaped
cat > "$TMP/q.md" <<'MD'
---
name: q-agent
description: use when: it says "hello" to you
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/q.md")"
if printf '%s\n' "$out" | grep -q 'description: "use when: it says \\"hello\\" to you"'; then pass esc-desc; else bad esc-desc; fi

# Case 5: missing frontmatter -> exit 1
printf 'no frontmatter\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 6: missing description -> exit 1
printf -- '---\nname: only-name\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 7: model inherit -> no model line
cat > "$TMP/inh.md" <<'MD'
---
name: inh-agent
description: inherits default
model: inherit
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/inh.md")"
if printf '%s\n' "$out" | grep -q '^model:'; then bad inherit-omit; else pass inherit-omit; fi

# Case 8: unknown model -> no model line + stderr warning
cat > "$TMP/unk.md" <<'MD'
---
name: unk-agent
description: has a literal model id
model: gpt-4
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/unk.md" 2>"$TMP/err")"
if printf '%s\n' "$out" | grep -q '^model:'; then bad unknown-omit; else pass unknown-omit; fi
if [ -s "$TMP/err" ]; then pass unknown-warn; else bad unknown-warn; fi

exit $fail
