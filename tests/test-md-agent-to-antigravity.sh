#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-agent-to-antigravity.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: a normal agent -> full frontmatter, no tools field
cat > "$TMP/basic.md" <<'MD'
---
name: basic-agent
description: use this agent when reviewing things
tools: Read, Grep
model: sonnet
---
You are a basic agent.
MD
out="$(python3 "$CONVERT" "$TMP/basic.md")"
printf '%s\n' "$out" | head -1 | grep -qx -- '---' && pass fm-first-line || bad fm-first-line
printf '%s\n' "$out" | sed -n '2p' | grep -q '^# GENERATED by install.sh' && pass banner-line2 || bad banner-line2
printf '%s\n' "$out" | grep -qx 'name: basic-agent' && pass name || bad name
printf '%s\n' "$out" | grep -qx 'mainAgent: false' && pass main-agent || bad main-agent
printf '%s\n' "$out" | grep -qx 'subagent: true' && pass subagent || bad subagent
printf '%s\n' "$out" | grep -qx 'model: pro' && pass model-sonnet || bad model-sonnet
printf '%s\n' "$out" | grep -q '^tools:' && bad no-tools || pass no-tools
printf '%s\n' "$out" | grep -q 'You are a basic agent.' && pass body || bad body

# Case 2: haiku -> flash
cat > "$TMP/h.md" <<'MD'
---
name: h-agent
description: cheap agent
model: haiku
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/h.md")"
printf '%s\n' "$out" | grep -qx 'model: flash' && pass model-haiku || bad model-haiku

# Case 3: name absent -> derived from the filename stem
cat > "$TMP/derived-name.md" <<'MD'
---
description: no name field at all
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/derived-name.md")"
printf '%s\n' "$out" | grep -qx 'name: derived-name' && pass name-from-filename || bad name-from-filename

# Case 4: description with a colon and double quotes -> escaped
cat > "$TMP/q.md" <<'MD'
---
name: q-agent
description: use when: it says "hello" to you
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/q.md")"
printf '%s\n' "$out" | grep -q 'description: "use when: it says \\"hello\\" to you"' && pass esc-desc || bad esc-desc

# Case 5: missing frontmatter -> exit 1
printf 'no frontmatter\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 6: missing description -> exit 1
printf -- '---\nname: only-name\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 7: model inherit -> no model line
cat > "$TMP/inh.md" <<'MD'
---
name: inh-agent
description: inherits default
model: inherit
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/inh.md")"
printf '%s\n' "$out" | grep -q '^model:' && bad inherit-omit || pass inherit-omit

# Case 8: unknown model -> no model line + stderr warning
cat > "$TMP/unk.md" <<'MD'
---
name: unk-agent
description: has a literal model id
model: gpt-4
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/unk.md" 2>"$TMP/err")"
printf '%s\n' "$out" | grep -q '^model:' && bad unknown-omit || pass unknown-omit
[ -s "$TMP/err" ] && pass unknown-warn || bad unknown-warn

exit $fail
