#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-agent-to-toml.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0

pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: basic conversion
cat > "$TMP/basic.md" <<'MD'
---
name: sample-agent
description: use this when testing
tools: Read, Bash
model: sonnet
color: cyan
---
You are a sample agent.
Do the thing.
MD
out="$(python3 "$CONVERT" "$TMP/basic.md")"
echo "$out" | grep -qx 'name = "sample-agent"' && pass name || bad name
echo "$out" | grep -qx 'description = "use this when testing"' && pass desc || bad desc
echo "$out" | grep -q 'developer_instructions = """' && pass di-open || bad di-open
echo "$out" | grep -q 'You are a sample agent.' && pass di-body || bad di-body
echo "$out" | grep -q '^# GENERATED by install.sh' && pass banner || bad banner
echo "$out" | grep -qx 'model = "gpt-5.4"' && pass model-sonnet || bad model-sonnet
echo "$out" | grep -qx 'model_reasoning_effort = "medium"' && pass effort-sonnet || bad effort-sonnet
echo "$out" | grep -q 'tools' && bad no-tools || pass no-tools

# Case 2: description with a colon and double quotes
cat > "$TMP/quotes.md" <<'MD'
---
name: q-agent
description: use when: it says "hello" to you
---
Body with "quotes" inside.
MD
out="$(python3 "$CONVERT" "$TMP/quotes.md")"
echo "$out" | grep -q 'description = "use when: it says \\"hello\\" to you"' && pass esc-desc || bad esc-desc

# Case 3: body containing a triple-quote and a backslash
printf -- '---\nname: tricky\ndescription: d\n---\nhas """ triple and \\ backslash\n' > "$TMP/tricky.md"
out="$(python3 "$CONVERT" "$TMP/tricky.md")"
python3 - "$TMP/tricky.md" <<'PY' && pass roundtrip || bad roundtrip
import subprocess, sys, tomllib
toml = subprocess.check_output([sys.executable, "scripts/md-agent-to-toml.py", sys.argv[1]])
data = tomllib.loads(toml.decode())
assert 'triple' in data['developer_instructions']
assert '\\' in data['developer_instructions']
PY

# Case 4: missing frontmatter -> exit 1
printf 'no frontmatter here\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 5: missing required field -> exit 1
printf -- '---\nname: only-name\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 6: opus -> gpt-5.5 / high
printf -- '---\nname: a\ndescription: d\nmodel: opus\n---\nBody.\n' > "$TMP/opus.md"
out="$(python3 "$CONVERT" "$TMP/opus.md")"
echo "$out" | grep -qx 'model = "gpt-5.5"' && pass opus-model || bad opus-model
echo "$out" | grep -qx 'model_reasoning_effort = "high"' && pass opus-effort || bad opus-effort

# Case 7: haiku -> gpt-5.4-mini / low
printf -- '---\nname: a\ndescription: d\nmodel: haiku\n---\nBody.\n' > "$TMP/haiku.md"
out="$(python3 "$CONVERT" "$TMP/haiku.md")"
echo "$out" | grep -qx 'model = "gpt-5.4-mini"' && pass haiku-model || bad haiku-model

# Case 8: inherit -> no model line
printf -- '---\nname: a\ndescription: d\nmodel: inherit\n---\nBody.\n' > "$TMP/inh.md"
out="$(python3 "$CONVERT" "$TMP/inh.md")"
echo "$out" | grep -q '^model = ' && bad inherit-omit || pass inherit-omit

# Case 9: absent model field -> no model line
printf -- '---\nname: a\ndescription: d\n---\nBody.\n' > "$TMP/absent.md"
out="$(python3 "$CONVERT" "$TMP/absent.md")"
echo "$out" | grep -q '^model = ' && bad absent-omit || pass absent-omit

# Case 10: unknown value -> no model line + stderr warning, exit 0
printf -- '---\nname: a\ndescription: d\nmodel: gpt-4\n---\nBody.\n' > "$TMP/unk.md"
out="$(python3 "$CONVERT" "$TMP/unk.md" 2>"$TMP/err")"
echo "$out" | grep -q '^model = ' && bad unknown-omit || pass unknown-omit
[ -s "$TMP/err" ] && pass unknown-warn || bad unknown-warn

exit $fail
