#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-agent-to-opencode.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: read-only agent (tools present, no Write/Edit/Bash) -> full lockdown
cat > "$TMP/ro.md" <<'MD'
---
name: ro-agent
description: use this when reviewing only
tools: Read
model: sonnet
---
You are a read-only agent.
MD
out="$(python3 "$CONVERT" "$TMP/ro.md")"
printf '%s\n' "$out" | head -1 | grep -qx -- '---' && pass fm-first-line || bad fm-first-line
printf '%s\n' "$out" | sed -n '2p' | grep -q '^# GENERATED by install.sh' && pass banner-line2 || bad banner-line2
printf '%s\n' "$out" | grep -qx 'mode: subagent' && pass mode || bad mode
printf '%s\n' "$out" | grep -qx '  write: false' && pass ro-write || bad ro-write
printf '%s\n' "$out" | grep -qx '  edit: false' && pass ro-edit || bad ro-edit
printf '%s\n' "$out" | grep -qx '  bash: false' && pass ro-bash || bad ro-bash
printf '%s\n' "$out" | grep -q 'You are a read-only agent.' && pass body || bad body
printf '%s\n' "$out" | grep -q '^name:' && bad no-name || pass no-name
printf '%s\n' "$out" | grep -qx 'model: opencode-go/deepseek-v4-pro' && pass model-sonnet || bad model-sonnet

# Case 2: writeable agent (tools include Write) -> no tools block
cat > "$TMP/rw.md" <<'MD'
---
name: rw-agent
description: use when editing files
tools: Bash, Read, Edit, Write, Glob, Grep
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/rw.md")"
printf '%s\n' "$out" | grep -q 'write: false' && bad rw-no-tools || pass rw-no-tools
printf '%s\n' "$out" | grep -qx 'mode: subagent' && pass rw-mode || bad rw-mode

# Case 3: read-only but has Bash -> write/edit false, NO bash false
cat > "$TMP/rb.md" <<'MD'
---
name: rb-agent
description: reviewer that runs commands
tools: Read, Grep, Glob, Bash
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/rb.md")"
printf '%s\n' "$out" | grep -qx '  write: false' && pass rb-write || bad rb-write
printf '%s\n' "$out" | grep -qx '  edit: false' && pass rb-edit || bad rb-edit
printf '%s\n' "$out" | grep -q 'bash: false' && bad rb-no-bash || pass rb-no-bash

# Case 4: tools absent entirely (full access) -> no tools block
cat > "$TMP/full.md" <<'MD'
---
name: full-agent
description: has all tools by omission
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/full.md")"
printf '%s\n' "$out" | grep -q 'write: false' && bad full-no-tools || pass full-no-tools

# Case 5: description with a colon and double quotes -> escaped
cat > "$TMP/q.md" <<'MD'
---
name: q-agent
description: use when: it says "hello" to you
tools: Read
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/q.md")"
printf '%s\n' "$out" | grep -q 'description: "use when: it says \\"hello\\" to you"' && pass esc-desc || bad esc-desc

# Case 6: missing frontmatter -> exit 1
printf 'no frontmatter\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 7: missing description -> exit 1
printf -- '---\nname: only-name\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 8: model inherit -> no model line
cat > "$TMP/inh.md" <<'MD'
---
name: inh-agent
description: inherits default
tools: Read
model: inherit
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/inh.md")"
printf '%s\n' "$out" | grep -q '^model:' && bad inherit-omit || pass inherit-omit

# Case 9: unknown model -> no model line + stderr warning
cat > "$TMP/unk.md" <<'MD'
---
name: unk-agent
description: has a literal model id
tools: Read
model: gpt-4
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/unk.md" 2>"$TMP/err")"
printf '%s\n' "$out" | grep -q '^model:' && bad unknown-omit || pass unknown-omit
[ -s "$TMP/err" ] && pass unknown-warn || bad unknown-warn

exit $fail
