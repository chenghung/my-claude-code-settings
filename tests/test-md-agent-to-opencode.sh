#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
CONVERT="$REPO/scripts/md-agent-to-opencode.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0
pass() { printf 'PASS %s\n' "$1"; }
bad()  { printf 'FAIL %s\n' "$1"; fail=1; }

# Case 1: read-only agent (tools present, no Write/Edit/Bash) -> full lockdown
cat > "$TMP/ro.md" <<'MD'
---
name: ro-agent
description: use this when reviewing only
tools: Read
model: sonnet
---
You are a read-only agent.
MD
out="$(python3 "$CONVERT" "$TMP/ro.md")"
if printf '%s\n' "$out" | head -1 | grep -qx -- '---'; then pass fm-first-line; else bad fm-first-line; fi
if printf '%s\n' "$out" | sed -n '2p' | grep -q '^# GENERATED by install.sh'; then pass banner-line2; else bad banner-line2; fi
if printf '%s\n' "$out" | grep -qx 'mode: subagent'; then pass mode; else bad mode; fi
if printf '%s\n' "$out" | grep -qx '  write: false'; then pass ro-write; else bad ro-write; fi
if printf '%s\n' "$out" | grep -qx '  edit: false'; then pass ro-edit; else bad ro-edit; fi
if printf '%s\n' "$out" | grep -qx '  bash: false'; then pass ro-bash; else bad ro-bash; fi
if printf '%s\n' "$out" | grep -q 'You are a read-only agent.'; then pass body; else bad body; fi
if printf '%s\n' "$out" | grep -q '^name:'; then bad no-name; else pass no-name; fi
if printf '%s\n' "$out" | grep -qx 'model: opencode-go/deepseek-v4-pro'; then pass model-sonnet; else bad model-sonnet; fi

# Case 2: writeable agent (tools include Write) -> no tools block
cat > "$TMP/rw.md" <<'MD'
---
name: rw-agent
description: use when editing files
tools: Bash, Read, Edit, Write, Glob, Grep
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/rw.md")"
if printf '%s\n' "$out" | grep -q 'write: false'; then bad rw-no-tools; else pass rw-no-tools; fi
if printf '%s\n' "$out" | grep -qx 'mode: subagent'; then pass rw-mode; else bad rw-mode; fi

# Case 3: read-only but has Bash -> write/edit false, NO bash false
cat > "$TMP/rb.md" <<'MD'
---
name: rb-agent
description: reviewer that runs commands
tools: Read, Grep, Glob, Bash
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/rb.md")"
if printf '%s\n' "$out" | grep -qx '  write: false'; then pass rb-write; else bad rb-write; fi
if printf '%s\n' "$out" | grep -qx '  edit: false'; then pass rb-edit; else bad rb-edit; fi
if printf '%s\n' "$out" | grep -q 'bash: false'; then bad rb-no-bash; else pass rb-no-bash; fi

# Case 4: tools absent entirely (full access) -> no tools block
cat > "$TMP/full.md" <<'MD'
---
name: full-agent
description: has all tools by omission
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/full.md")"
if printf '%s\n' "$out" | grep -q 'write: false'; then bad full-no-tools; else pass full-no-tools; fi

# Case 5: description with a colon and double quotes -> escaped
cat > "$TMP/q.md" <<'MD'
---
name: q-agent
description: use when: it says "hello" to you
tools: Read
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/q.md")"
if printf '%s\n' "$out" | grep -q 'description: "use when: it says \\"hello\\" to you"'; then pass esc-desc; else bad esc-desc; fi

# Case 6: missing frontmatter -> exit 1
printf 'no frontmatter\n' > "$TMP/nofm.md"
if python3 "$CONVERT" "$TMP/nofm.md" >/dev/null 2>&1; then bad missing-fm; else pass missing-fm; fi

# Case 7: missing description -> exit 1
printf -- '---\nname: only-name\n---\nbody\n' > "$TMP/nodesc.md"
if python3 "$CONVERT" "$TMP/nodesc.md" >/dev/null 2>&1; then bad missing-desc; else pass missing-desc; fi

# Case 8: model inherit -> no model line
cat > "$TMP/inh.md" <<'MD'
---
name: inh-agent
description: inherits default
tools: Read
model: inherit
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/inh.md")"
if printf '%s\n' "$out" | grep -q '^model:'; then bad inherit-omit; else pass inherit-omit; fi

# Case 9: unknown model -> no model line + stderr warning
cat > "$TMP/unk.md" <<'MD'
---
name: unk-agent
description: has a literal model id
tools: Read
model: gpt-4
---
Body.
MD
out="$(python3 "$CONVERT" "$TMP/unk.md" 2>"$TMP/err")"
if printf '%s\n' "$out" | grep -q '^model:'; then bad unknown-omit; else pass unknown-omit; fi
if [ -s "$TMP/err" ]; then pass unknown-warn; else bad unknown-warn; fi

exit $fail
